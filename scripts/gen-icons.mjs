#!/usr/bin/env node
/**
 * Generates src/app/core/icons.generated.ts from @material-symbols/svg-400.
 *
 * Only the icons listed below end up in the bundle, as inline SVG strings, so the app
 * needs no icon font and no network access. Re-run with `npm run icons` after editing
 * the list.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'node_modules/@material-symbols/svg-400/outlined');

/** App icon name → Material Symbols file name (without .svg). */
const ICONS = {
  'account-tree': 'account_tree',
  add: 'add',
  'add-photo': 'add_a_photo',
  'arrow-back': 'arrow_back',
  backup: 'backup',
  box: 'package_2',
  camera: 'photo_camera',
  check: 'check',
  'check-circle': 'check_circle',
  'chevron-left': 'chevron_left',
  'chevron-right': 'chevron_right',
  close: 'close',
  delete: 'delete',
  deselect: 'deselect',
  download: 'download',
  edit: 'edit',
  'expand-more': 'keyboard_arrow_down',
  'expand-right': 'keyboard_arrow_right',
  folder: 'folder',
  history: 'history',
  home: 'home',
  image: 'image',
  info: 'info',
  'more-vert': 'more_vert',
  move: 'drive_file_move',
  public: 'public',
  search: 'search',
  'select-all': 'select_all',
  settings: 'settings',
  share: 'share',
  star: 'star-fill',
  'star-outline': 'star',
  storage: 'hard_drive',
  tag: 'sell',
  'top-level': 'vertical_align_top',
  upload: 'upload_file',
  warning: 'warning',
};

const entries = Object.entries(ICONS).map(([name, file]) => {
  const svg = readFileSync(join(source, `${file}.svg`), 'utf8')
    .trim()
    .replace(/ width="48" height="48"/, '')
    .replace('<svg ', '<svg fill="currentColor" ');
  return `  '${name}': '${svg.replace(/'/g, "\\'")}',`;
});

const out = `// GENERATED by scripts/gen-icons.mjs – do not edit by hand.
// Icons: Material Symbols (Apache License 2.0), https://github.com/google/material-design-icons

export const ICONS: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`;

writeFileSync(join(root, 'src/app/core/icons.generated.ts'), out);
console.log(`Wrote ${entries.length} icons.`);
